// ============================================================
//  server.js — سيرفر استضافة مكتبة Html3D.js
// ------------------------------------------------------------
//  هذا السيرفر يجعل مكتبتك (Html3D.js وكل ملفاتها المساعدة) قابلة
//  للاستيراد عبر رابط، تماماً كما تستورد three.js من CDN:
//
//      import { HtmlDomParser } from 'https://your-domain.com/lib/Html3D.js';
//
//  طريقة التشغيل:
//    1) npm install
//    2) node server.js        (أو: npm start)
//
//  السيرفر يعمل افتراضياً على المنفذ 3000، ويقرأ الملفات من مجلد
//  public/ المجاور لهذا الملف. ضع مكتبتك بالكامل داخل public/ محافظاً
//  على نفس هيكل المجلدات الذي تستخدمه محلياً بالضبط، مثلاً:
//
//      public/
//        lib/
//          Html3D.js
//        js/
//          csg-ops.js
//          bevel-ops.js
//          animation-system.js
//          effects-system.js
//          texture-ops.js
//
//  هذا مهم لأن Html3D.js يستورد هذه الملفات بمسارات نسبية (../js/...)،
//  وهذه المسارات تُحل بالنسبة لموقع الملف نفسه على السيرفر — فطالما
//  البنية محفوظة كما هي، ستعمل الاستيرادات صحيحة تلقائياً بغض النظر
//  عن اسم نطاقك أو مساره.
// ============================================================

const express = require('express');
const cors = require('cors');
const path = require('path');

const app = express();
const PORT = process.env.PORT || 3000;
const ROOT_DIR = path.join(__dirname, 'public');

// ------------------------------------------------------------
// ✅ الخطوة الأهم: تفعيل CORS
// ------------------------------------------------------------
// بدون هذا، أي صفحة على نطاق مختلف عن سيرفرك سيفشل فيها "import" لملفات
// مكتبتك — المتصفح يمنعها تلقائياً (خطأ CORS يظهر في الكونسول) لأن
// "import" عبر الشبكة يُعامَل مثل طلب fetch عادي من ناحية سياسات الأمان.
//
// origin: '*' يعني السماح لأي موقع باستيراد مكتبتك (مناسب لمكتبة عامة
// يستخدمها آخرون). إن أردت لاحقاً قصرها على مواقع محددة فقط، استبدلها بـ:
//   app.use(cors({ origin: ['https://example.com', 'https://myapp.com'] }));
app.use(cors({ origin: '*' }));

// ------------------------------------------------------------
// ✅ ضبط الأنواع (MIME types) بشكل صريح لملفات JS
// ------------------------------------------------------------
// express.static يضبط نوع ملفات .js بشكل صحيح تلقائياً على أغلب
// الأنظمة، لكننا نفرضها هنا صراحة لتفادي أي خلل: المتصفح يرفض تنفيذ
// "import" لملف إن لم يكن نوعه application/javascript أو text/javascript
// (بعض الإعدادات الافتراضية القديمة تُرجع text/plain وهذا يكسر الاستيراد).
app.use(express.static(ROOT_DIR, {
    setHeaders: (res, filePath) => {
        if (filePath.endsWith('.js') || filePath.endsWith('.mjs')) {
            res.setHeader('Content-Type', 'text/javascript; charset=utf-8');
        }
        // ⚠️ أثناء التطوير: نمنع الكاش نهائياً حتى ترى أي تعديل تجريه على
        // ملفاتك فوراً في المتصفح دون الحاجة لمسح الكاش يدوياً. عند النشر
        // الفعلي ورضاك عن استقرار نسخة معينة، يمكنك استبدال هذا بشيء مثل:
        //   res.setHeader('Cache-Control', 'public, max-age=31536000, immutable');
        // مع تغيير مسار الاستضافة (مثلاً public/v1 -> public/v2) عند كل
        // تحديث حقيقي، حتى لا يبقى مستخدمو المكتبة عالقين بنسخة قديمة مخبأة
        // في متصفحاتهم، ولا ينكسر عملهم فجأة عند كل تعديل تنشره.
        res.setHeader('Cache-Control', 'no-store');
    }
}));

// ------------------------------------------------------------
// فحص سريع للتأكد أن السيرفر يعمل (افتح الرابط في المتصفح)
// ------------------------------------------------------------
app.get('/health', (req, res) => {
    res.send('✅ Html3D library server is running.');
});

app.listen(PORT, () => {
    console.log(`✅ Html3D library server running at: http://localhost:${PORT}`);
    console.log(`   يخدم الملفات من: ${ROOT_DIR}`);
    console.log(`   مثال رابط اختبار: http://localhost:${PORT}/lib/Html3D.js`);
    console.log(`   فحص الحالة: http://localhost:${PORT}/health`);
});
